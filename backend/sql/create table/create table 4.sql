CREATE TABLE IF NOT EXISTS "PROGRAMACION_GRUPO" (
    "ID_PROGRAMACION" INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    "ID_GRUPO" INTEGER NOT NULL,
    "DIA_IDX" INTEGER NOT NULL CHECK ("DIA_IDX" > 0),
    "ID_BLOQUE" INTEGER NOT NULL,
    "ID_GRUPO_PLAN_CURSO" INTEGER NULL,
    "ACTIVO" BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT "FK_PROG_GRUPO"
    FOREIGN KEY ("ID_GRUPO") REFERENCES "GRUPOS" ("ID_GRUPO")
    ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "FK_PROG_BLOQUE"
    FOREIGN KEY ("ID_BLOQUE") REFERENCES "HORARIO_BLOQUES" ("ID_BLOQUE")
    ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "FK_PROG_GRUPO_PLAN_CURSO"
    FOREIGN KEY ("ID_GRUPO_PLAN_CURSO") REFERENCES "GRUPO_PLAN_CURSO" ("ID_GRUPO_PLAN_CURSO")
    ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT "UQ_PROG_GRUPO_DIA_BLOQUE"
    UNIQUE ("ID_GRUPO", "DIA_IDX", "ID_BLOQUE")
);

CREATE INDEX IF NOT EXISTS "IDX_PROG_GRUPO_DIA_BLOQUE"

ON "PROGRAMACION_GRUPO" ("ID_GRUPO", "DIA_IDX", "ID_BLOQUE");

CREATE INDEX IF NOT EXISTS "IDX_PROG_GRUPO_PLAN_CURSO"

ON "PROGRAMACION_GRUPO" ("ID_GRUPO_PLAN_CURSO");
